package io.element.android.libraries.accountemail.api

/**
 * Знает, привязана ли к аккаунту почта, и когда об этом стоит напомнить.
 *
 * Почтой в нашей схеме владеет MAS, а не Synapse: человек добавляет её на странице
 * аккаунта, MAS подтверждает адрес 6-значным кодом и после этого сам прокидывает его в
 * Synapse. Поэтому клиенту достаточно штатного `/account/3pid`, свои ручки не нужны.
 */
interface AccountEmailStatus {
    /**
     * Привязана ли почта.
     *
     * `null` означает «выяснить не удалось» (нет сети, сервер ответил ошибкой) и это не
     * то же самое, что `false`: на «не удалось» баннер показывать нельзя, иначе человек
     * с привязанной почтой увидит его в самолётном режиме.
     */
    suspend fun hasEmail(): Boolean?

    /** Скрыт ли сейчас баннер: человек его закрывал и срок молчания ещё не вышел. */
    suspend fun isBannerHidden(): Boolean

    /** Запомнить, что баннер закрыли. */
    suspend fun hideBanner()
}
