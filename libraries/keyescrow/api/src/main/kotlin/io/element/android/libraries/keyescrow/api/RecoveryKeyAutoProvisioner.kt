package io.element.android.libraries.keyescrow.api

/**
 * Молча гарантирует, что у аккаунта есть ключ восстановления и он лежит в escrow.
 *
 * Зачем: без ключа восстановления сессия после переустановки/сброса не может верифицироваться
 * (кросс-подпись и бэкап не восстанавливаются) → у неё ломается раздача/приём Megolm-ключей →
 * собеседники не видят её сообщений (UTD). Если же ключ восстановления есть и заескроен, любая
 * новая сессия восстанавливается кодом с почты, остаётся кросс-подписанной, и UTD не возникает.
 *
 * Пользователь ключ не видит — его роль играет код с почты (см. [KeyEscrowService]).
 */
interface RecoveryKeyAutoProvisioner {
    /**
     * Если у аккаунта ещё нет восстановления (`RecoveryState.DISABLED` — свежий аккаунт, а не
     * сброшенная сессия с уже существующим бэкапом), создать ключ восстановления и залить в escrow.
     * Идемпотентно: при уже настроенном восстановлении ничего не делает.
     */
    suspend fun ensureProvisioned()
}
