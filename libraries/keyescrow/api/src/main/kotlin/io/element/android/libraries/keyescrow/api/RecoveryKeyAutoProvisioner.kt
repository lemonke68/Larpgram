package io.element.android.libraries.keyescrow.api

import kotlinx.coroutines.flow.StateFlow

/**
 * Молча гарантирует, что у аккаунта есть ключ восстановления и новая сессия открывает историю
 * без второго устройства.
 *
 * Зачем: без ключа восстановления сессия после переустановки/сброса не может верифицироваться
 * (кросс-подпись и бэкап не восстанавливаются) → у неё ломается раздача/приём Megolm-ключей →
 * собеседники не видят её сообщений (UTD).
 *
 * Вариант B (larpgram-infra, этап 7): ключ запирается паролем аккаунта на клиенте и в таком виде
 * лежит на сервере ([LockedRecoveryKey]); сервер его открыть не может. Новая сессия отпирает его
 * паролем, которым только что вошла ([LoginPasswordHandoff]). Копия ключа хранится на устройстве
 * под ключом Android Keystore, ею любое вошедшее устройство перезапирает блоб, например после
 * смены пароля. Ключ на сервере в открытом для него виде остаётся только у тех, кто включил
 * «восстановление через сервер».
 */
interface RecoveryKeyAutoProvisioner {
    /**
     * Приводит аккаунт и сессию к «ключ заперт паролем на сервере, копия на устройстве, сессия
     * подписана». Идемпотентно, безопасно звать параллельно.
     */
    suspend fun ensureProvisioned()

    /**
     * `true` — ключ восстановления есть, но на сервере не заперт текущим паролем, а пароля под рукой
     * нет (вошли по QR, старый аккаунт до варианта B). Тогда приложение просит пароль один раз.
     */
    val needsPassword: StateFlow<Boolean>

    /** Запереть ключ паролем и положить на сервер. Пароль вызывающий уже проверил. */
    suspend fun lockWithPassword(password: String): Result<Unit>

    /** Пароль сменили в приложении: перезапереть ключ новым, история на новых устройствах не теряется. */
    suspend fun onPasswordChanged(newPassword: String)

    /** Ключ создали вручную (экраны Element про ключ восстановления): сохранить и запереть. */
    suspend fun onRecoveryKeyCreated(recoveryKey: String)
}
